import { Injectable, Logger } from '@nestjs/common';
import { MemoryService } from '../../../memory/memory.service';
import type { MemoryKind, Sensitivity } from '../../../memory/memory.types';

/**
 * `saveMemory` — the write half of long-term memory, as a tool.
 *
 * The four gates live inside the service, not here and not in the prompt:
 * a model that hallucinates a quote gets `stored: false`, and no amount of
 * persuasive JSON changes that. The model's only real job is deciding
 * *what* is worth remembering.
 *
 * Returns a structured verdict rather than a sentence — the reply the
 * child hears is generated by the current age-group prompt, so a refusal
 * never surfaces as "保存失败" to a five-year-old.
 */
@Injectable()
export class SaveMemoryTool {
  private readonly logger = new Logger(SaveMemoryTool.name);

  constructor(private readonly memoryService: MemoryService) {}

  async execute(args: {
    childId: number;
    content: string;
    verbatimQuote: string;
    kind?: MemoryKind;
    occurredAt?: string;
    confidence?: number;
    sensitivity?: Sensitivity;
    secrets?: string[];
    sessionId?: string;
  }): Promise<string> {
    if (!args?.childId || !args?.content?.trim() || !args?.verbatimQuote?.trim()) {
      return JSON.stringify({ stored: false, reason: 'empty_content' });
    }

    try {
      const result = await this.memoryService.saveMemory({
        childId: args.childId,
        sessionId: args.sessionId,
        content: args.content,
        verbatimQuote: args.verbatimQuote,
        kind: args.kind,
        occurredAt: args.occurredAt ?? null,
        confidence: args.confidence,
        sensitivity: args.sensitivity,
        secrets: args.secrets,
      });

      return JSON.stringify({
        stored: result.stored,
        ...(result.reason ? { reason: result.reason } : {}),
        ...(result.memoryId != null ? { memoryId: result.memoryId } : {}),
        hint: result.stored ? HINTS.stored : HINTS.rejected,
      });
    } catch (err) {
      this.logger.error(`saveMemory tool failed: ${(err as Error).message}`);
      return JSON.stringify({ stored: false, reason: 'empty_content' });
    }
  }
}

const HINTS = {
  stored: '记下了。不要向孩子复述"我记住了"这类系统语言，自然地继续聊就好。',
  rejected: '这次没能记下（不要向孩子解释原因，也不要道歉说系统问题）。继续正常对话即可。',
};
